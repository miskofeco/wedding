// Regenerates public/art/<ink>/<name>.svg from the original pack.
// The pack's outlines are filled paths without a fill attribute, so the ink is
// one attribute on the root <svg>. Illustrator metadata and whitespace are
// dropped. Coordinates are kept exact: paths are relative, so rounding drifts
// and breaks the thin filled outlines.
import { readFile, writeFile, mkdir, rm } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const packDir = path.resolve(root, "../doodles/whimsical");
const outDir = path.join(root, "public/art");
const manifest = JSON.parse(await readFile(path.join(root, "art-manifest.json"), "utf8"));

const clean = (svg, fill) =>
  svg
    .replace(/<\?xml[^>]*\?>/g, "")
    .replace(/<!--[\s\S]*?-->/g, "")
    .replace(/<svg[^>]*?viewBox="([^"]+)"[^>]*>/, `<svg xmlns="http://www.w3.org/2000/svg" viewBox="$1" fill="${fill}">`)
    .replace(/\s+/g, " ")
    .replace(/>\s+</g, "><")
    .trim();

// A crop takes one figure out of a drawing: `box` [x, y, w, h] on the 1080
// artboard becomes the viewBox, and an optional `clip` polygon hides the rest
// of the scene inside the box (a partner's hand, say).
const cropTo = (svg, { box, clip }) => {
  let out = svg.replace(/viewBox="[^"]+"/, `viewBox="${box.join(" ")}"`);
  if (clip) {
    out = out
      .replace(/(<svg[^>]*>)/, `$1<defs><clipPath id="crop"><polygon points="${clip.map((p) => p.join(",")).join(" ")}"/></clipPath></defs><g clip-path="url(#crop)">`)
      .replace(/<\/svg>$/, "</g></svg>");
  }
  return out;
};

await rm(outDir, { recursive: true, force: true });
let total = 0;
for (const d of manifest.drawings) {
  const raw = await readFile(path.join(packDir, d.source), "utf8");
  if (!/viewBox="0 0 1080 1080"/.test(raw)) throw new Error(`Unexpected artboard in ${d.source}`);
  for (const ink of d.inks) {
    const hex = manifest.inks[ink];
    if (!hex) throw new Error(`Unknown ink ${ink} for ${d.name}`);
    const out = d.crop ? cropTo(clean(raw, hex), d.crop) : clean(raw, hex);
    await mkdir(path.join(outDir, ink), { recursive: true });
    await writeFile(path.join(outDir, ink, `${d.name}.svg`), out + "\n");
    total += out.length;
  }
}
const map = Object.fromEntries(manifest.drawings.map((d) => [d.name, d.inks]));
const ts = `// Generated by scripts/sync-art.mjs from art-manifest.json. Do not edit.
export const drawings = ${JSON.stringify(map, null, 2)} as const;
`;
await writeFile(path.join(root, "src/lib/art.generated.ts"), ts);
console.log(`Wrote ${manifest.drawings.length} drawings, ${(total / 1024).toFixed(0)} KB in public/art`);
